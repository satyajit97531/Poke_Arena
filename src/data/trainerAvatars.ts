export interface TrainerAvatar {
  id: string;
  numericId?: number;
  name: string;
  title: string;
  role: string;
  region: string;
  spriteUrl: string;
  rarity: 'normal' | 'rare' | 'super_rare' | 'epic' | 'mythic' | 'legendary';
  tokenCost: number;
  howToUnlock: string;
  isDefaultUnlocked?: boolean;
  category?: 'champion' | 'gym_leader' | 'coordinator_special';
  description?: string;
  frameBorder?: string;
  badgeClass?: string;
}

export function getTrainerFrameBorder(rarity: TrainerAvatar['rarity']): string {
  switch (rarity) {
    case 'legendary':
      return 'border-2 border-amber-400/80 bg-gradient-to-b from-amber-500/15 via-slate-900 to-slate-950 shadow-lg shadow-amber-950/50';
    case 'mythic':
      return 'border-2 border-purple-400/80 bg-gradient-to-b from-purple-500/15 via-slate-900 to-slate-950 shadow-lg shadow-purple-950/50';
    case 'epic':
      return 'border-2 border-rose-400/70 bg-gradient-to-b from-rose-500/15 via-slate-900 to-slate-950 shadow-md shadow-rose-950/40';
    case 'super_rare':
      return 'border border-cyan-400/60 bg-gradient-to-b from-cyan-500/10 via-slate-900 to-slate-950';
    case 'rare':
      return 'border border-blue-400/50 bg-gradient-to-b from-blue-500/10 via-slate-900 to-slate-950';
    default:
      return 'border border-slate-800 bg-slate-950/70';
  }
}

export function getTrainerBadgeClass(rarity: TrainerAvatar['rarity']): string {
  switch (rarity) {
    case 'legendary':
      return 'bg-amber-500/20 text-amber-300 border-amber-400/40';
    case 'mythic':
      return 'bg-purple-500/20 text-purple-300 border-purple-400/40';
    case 'epic':
      return 'bg-rose-500/20 text-rose-300 border-rose-400/40';
    case 'super_rare':
      return 'bg-cyan-500/20 text-cyan-300 border-cyan-400/40';
    case 'rare':
      return 'bg-blue-500/20 text-blue-300 border-blue-400/40';
    default:
      return 'bg-slate-800 text-slate-300 border-slate-700';
  }
}

